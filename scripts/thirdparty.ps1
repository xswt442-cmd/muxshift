# Writes the third-party notice for the desktop build.
#
# The list is read from the two modules this repository builds (the root module
# and desktop, which is a module of its own), so it follows go.mod rather than
# someone's memory. Each entry names the version and the licence the module copy
# ships; a module with no licence file is written as such rather than guessed.
#
# External runtime dependencies (ffmpeg, ffprobe, the WebView2 runtime) are not
# Go modules and are not distributed with this build; they are listed apart.
param(
    [string]$Out = "dist\THIRD-PARTY.md"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot

function Get-Modules([string]$workdir) {
    # The modules the shipped binary actually links, not everything go.mod
    # mentions: a test-only dependency is not in the release.
    Push-Location $workdir
    try {
        $lines = & go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}' ./
        foreach ($line in $lines) {
            if ([string]::IsNullOrWhiteSpace($line)) { continue }
            $parts = $line.Split('|')
            if ($parts.Length -lt 3) { continue }
            [pscustomobject]@{ Path = $parts[0]; Version = $parts[1]; Dir = $parts[2] }
        }
    }
    finally {
        Pop-Location
    }
}

function Get-Licence([string]$dir) {
    if ([string]::IsNullOrWhiteSpace($dir) -or -not (Test-Path $dir)) {
        return @{ Name = "module copy not on this machine"; File = $null; Text = $null }
    }
    $file = Get-ChildItem -Path $dir -File | Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING)' } | Select-Object -First 1
    if ($null -eq $file) {
        return @{ Name = "no licence file in the module copy"; File = $null; Text = $null }
    }
    $text = [IO.File]::ReadAllText($file.FullName)
    $name = "other (see the file)"
    if ($text -match 'Apache License') { $name = "Apache-2.0" }
    elseif ($text -match 'MIT License|Permission is hereby granted, free of charge') { $name = "MIT" }
    elseif ($text -match 'Redistribution and use in source and binary forms') { $name = "BSD" }
    elseif ($text -match 'ISC License|Permission to use, copy, modify, and/or distribute') { $name = "ISC" }
    elseif ($text -match 'Mozilla Public License') { $name = "MPL-2.0" }
    return @{ Name = $name; File = $file.Name; Text = $text }
}

$modules = @()
$modules += Get-Modules (Join-Path $root "desktop")
$modules = $modules | Sort-Object Path -Unique

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# Third-party notices")
$lines.Add("")
$lines.Add("This file is generated by ``scripts/thirdparty.ps1`` from the two Go modules")
$lines.Add("this repository builds. It lists what the desktop binary links, not what the")
$lines.Add("machine it runs on provides.")
$lines.Add("")
$lines.Add("## Go modules")
$lines.Add("")
$lines.Add("| module | version | licence |")
$lines.Add("| --- | --- | --- |")
foreach ($module in $modules) {
    $licence = Get-Licence $module.Dir
    $lines.Add("| ``$($module.Path)`` | $($module.Version) | $($licence.Name) |")
}
$lines.Add("")
$lines.Add("## Bundled in this repository")
$lines.Add("")
$lines.Add("| component | licence | where |")
$lines.Add("| --- | --- | --- |")
$lines.Add("| hls.js (light build) | Apache-2.0 | ``web/vendor/hls.light.min.js``, text in ``web/vendor/hls.LICENSE`` |")
$lines.Add("| MuxShift itself | see ``LICENSE`` | the repository root |")
$lines.Add("")
$lines.Add("## Needed at run time, not distributed")
$lines.Add("")
$lines.Add("| component | why | licence |")
$lines.Add("| --- | --- | --- |")
$lines.Add("| ffmpeg and ffprobe | decoding for alignment and measuring a recording's first timestamp | the build of ffmpeg on the machine decides (LGPL or GPL); this repository ships none |")
$lines.Add("| Microsoft Edge WebView2 runtime | only when the optional web control panel is started | Microsoft's terms for the runtime |")
$lines.Add("| vocal separation weights (``tools/separate``) | not part of the desktop binary and not shipped | unconfirmed upstream; the tool asks for an explicit ``--model`` |")
$lines.Add("")
$lines.Add("## Licence texts")
$lines.Add("")
$lines.Add("Each module's own licence file is reproduced below, so a release can be")
$lines.Add("handed on without the module cache it was built from.")
$lines.Add("")
foreach ($module in $modules) {
    $text = Get-Licence $module.Dir
    $lines.Add("### $($module.Path) $($module.Version) - $($text.Name)")
    $lines.Add("")
    if ($null -eq $text.Text) {
        $lines.Add("(no licence file in the module copy; the upstream module is the authority)")
    }
    else {
        $lines.Add('``````')
        foreach ($row in ($text.Text -split "`r?`n")) { $lines.Add($row) }
        $lines.Add('``````')
    }
    $lines.Add("")
}
$lines.Add("### hls.js light - Apache-2.0")
$lines.Add("")
$hlsLicence = Join-Path $root "web\vendor\hls.LICENSE"
if (Test-Path $hlsLicence) {
    $lines.Add('``````')
    foreach ($row in (([IO.File]::ReadAllText($hlsLicence)) -split "`r?`n")) { $lines.Add($row) }
    $lines.Add('``````')
}
else {
    $lines.Add("(web/vendor/hls.LICENSE is missing from this checkout)")
}
$lines.Add("The licence texts themselves are the ones in each module's own copy; this")
$lines.Add("notice names them so a release can be checked without reading every module.")

$target = Join-Path $root $Out
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
[IO.File]::WriteAllText($target, ($lines -join "`n") + "`n", (New-Object Text.UTF8Encoding($false)))
Write-Output "wrote $target ($($modules.Count) module(s))"
